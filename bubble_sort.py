# ============================================================
# 冒泡排序（Bubble Sort）Python 实现
# 功能：读入 n 个整数，按从小到大排序后输出
# 运行：python3 bubble_sort.py
# ------------------------------------------------------------
# 算法思想：
#   重复遍历待排序序列，每次比较相邻两个元素。
#   若前一个比后一个大，就交换它们。
#   每遍历一趟，当前未排序部分中最大的元素就会
#   "浮" 到末尾，如同气泡上浮，故称冒泡排序。
# ============================================================


def bubble_sort(a):
    """原地对列表 a 做升序冒泡排序。"""
    n = len(a)

    # i 表示已完成的趟数：每趟结束后，末尾 i+1 个元素已排好序
    for i in range(n - 1):
        swapped = False                    # 记录本趟是否发生交换

        # j 遍历尚未排序的前 n-1-i 个元素
        # 因为末尾 i 个元素已经有序，无需再比较
        for j in range(n - 1 - i):
            if a[j] > a[j + 1]:            # 前一个比后一个大：逆序，需要交换
                a[j], a[j + 1] = a[j + 1], a[j]   # Python 特有的交换写法
                swapped = True             # 标记本趟发生了交换

        # 优化：若本趟一次交换都没发生，说明序列已经有序，可提前结束
        if not swapped:
            break

    return a


def main():
    n = int(input())                       # n：数据个数
    a = list(map(int, input().split()))    # 读入 n 个整数

    bubble_sort(a)

    # 空格分隔输出，末尾换行
    print(' '.join(map(str, a)))


if __name__ == '__main__':
    main()