// ============================================================
// 信奥赛 C++ 冒泡排序（Bubble Sort）示例
// 功能：读入 n 个整数，按从小到大排序后输出
// 编译：g++ -std=c++14 -O2 -o bubble_sort bubble_sort.cpp
// 运行：./bubble_sort
// ------------------------------------------------------------
// 算法思想：
//   重复遍历待排序序列，每次比较相邻两个元素。
//   若前一个比后一个大，就交换它们。
//   每遍历一趟，当前未排序部分中最大的元素就会
//   "浮" 到末尾，如同气泡上浮，故称冒泡排序。
// ============================================================

#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n;
    cin >> n;                              // n：数据个数

    vector<int> a(n);                      // 用动态数组存放 n 个数
    for (int i = 0; i < n; i++) {
        cin >> a[i];                       // 依次读入每个数
    }

    // ---------- 冒泡排序核心 ----------
    // i 表示已完成的趟数：每趟结束后，末尾 i+1 个元素已排好序
    for (int i = 0; i < n - 1; i++) {
        bool swapped = false;              // 记录本趟是否发生交换

        // j 遍历尚未排序的前 n-1-i 个元素
        // 因为末尾 i 个元素已经有序，无需再比较
        for (int j = 0; j < n - 1 - i; j++) {
            if (a[j] > a[j + 1]) {         // 前一个比后一个大：逆序，需要交换
                swap(a[j], a[j + 1]);      // 交换相邻两元素
                swapped = true;            // 标记本趟发生了交换
            }
        }

        // 优化：若本趟一次交换都没发生，说明序列已经有序，可提前结束
        if (!swapped) break;
    }

    // ---------- 输出结果 ----------
    for (int i = 0; i < n; i++) {
        cout << a[i] << (i == n - 1 ? '\n' : ' ');  // 空格分隔，末尾换行
    }

    return 0;
}